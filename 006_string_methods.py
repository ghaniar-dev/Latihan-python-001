nama = " Ghaniar Ganteng "

print (nama.upper()) #membuat string menjadi kapital semua
print (nama.lower()) #membuat string menjadi kecil semua
print (nama.title()) #membuat string menjadi huruf pertama di setiap kata jadi kapital semua
print (nama.capitalize()) #membuat string menjadi huruf pertama di setiap kalimat jadi kapital
print (nama.strip()) #membuat spasi di awal dan di akhir
print (nama.replace("Ganteng", "Jelek")) #mengganti kata yang pertama menjadi kata yang ke dua
print (nama.count("a")) #menghitung ada berapa huruf itu di dalam variable nama (ini sensitif besar dan kecilnya huruf)
print (nama.find("Ganteng")) #mencari ada di index ke berapa kata tersebut
print (nama.swapcase()) #menukar yang kecil jadi besar dan yang besar menjadi kecil





